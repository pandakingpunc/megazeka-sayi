    """(girdi, hedef) çiftleri; DUSUR'dakiler alınmaz."""
    assert len(adaylar) == 466, len(adaylar)
    cikti = []
    for no, girdi in enumerate(adaylar, 1):
        if no in DUSUR:
            continue
        hedef = girdi
